test_that("records come back labelled, filtered, capped and without free text", {
  ctx <- test_ctx()
  cfg <- utils::modifyList(assistant_config(ctx$study), list(row_cap = 5L))
  tools <- assistant_tools(ctx, cfg)
  r <- tool(tools, "get_records")(form = "ae", filters = list("AESEV == severe"), limit = 500L)
  ae <- shiny::isolate(ctx$data())$tables$AE
  expect_equal(r$total_matches, sum(ae$AESEV == "SEVERE", na.rm = TRUE))
  expect_lte(r$returned, 5)
  expect_true(all(r$rows$AESEV == "SEVERE"))
  expect_false("AETERM" %in% names(r$rows))
  expect_false(any(c("ENTRYDT", "VERSION") %in% names(r$rows)))
  expect_equal(r$labels$AESEV, "Severity")
  one <- tool(tools, "get_records")(form = "SUBJECTS", subject = "101-001", fields = list("TRTSDT"))
  expect_equal(names(one$rows), c("SUBJID", "TRTSDT"))
  expect_type(one$rows$TRTSDT, "character")
  expect_error(tool(tools, "get_records")(form = "AE", filters = list("AETERM contains ACNE")), "withheld")
  expect_error(tool(tools, "get_records")(form = "AE", filters = list("AESEV is bad")), "FIELD OP VALUE")
  expect_error(tool(tools, "get_records")(form = "XX"), "No form")
  age <- tool(tools, "get_records")(form = "DM", filters = list("AGE >= 60"))
  expect_true(all(as.numeric(age$rows$AGE) >= 60))
})

test_that("counts group by up to two fields and refuse free text", {
  ctx <- test_ctx()
  tools <- assistant_tools(ctx, assistant_config(ctx$study))
  n <- tool(tools, "count_records")(form = "AE", by = list("AESEV"))
  ae <- shiny::isolate(ctx$data())$tables$AE
  expect_equal(sum(n$rows$records), nrow(ae))
  expect_true(all(c("AESEV", "records", "subjects") %in% names(n$rows)))
  expect_equal(tool(tools, "count_records")(form = "AE")$records, nrow(ae))
  expect_error(tool(tools, "count_records")(form = "AE", by = list("AETERM")), "withheld")
  expect_error(tool(tools, "count_records")(form = "AE", by = list("AESEV", "AESER", "AEREL")), "at most 2")
})

test_that("overview, form description and subject summary describe the review data", {
  ctx <- test_ctx()
  tools <- assistant_tools(ctx, assistant_config(ctx$study))
  o <- tool(tools, "study_overview")()
  expect_equal(o$study, "DERM-301-SIM")
  expect_equal(o$review_date, "2026-12-31")
  expect_true(all(c("SUBJECTS", "AE", "PK") %in% o$forms$form))
  expect_true("profile" %in% o$screens$screen)
  d <- tool(tools, "describe_form")(form = "AE")
  expect_true(d$fields$withheld_free_text[d$fields$field == "AETERM"])
  expect_equal(d$fields$values[d$fields$field == "AETERM"], "")
  expect_match(d$fields$values[d$fields$field == "AESEV"], "SEVERE")
  s <- tool(tools, "subject_summary")(subject = "101-001")
  expect_equal(s$subject$rows$SUBJID, "101-001")
  expect_gt(s$records_per_form$AE, 0)
  expect_error(tool(tools, "subject_summary")(subject = "999-999"), "No subject")
})

test_that("checks and findings come from the review checks, with free text withheld", {
  ctx <- test_ctx()
  tools <- assistant_tools(ctx, assistant_config(ctx$study))
  all_checks <- tool(tools, "list_checks")()
  ch <- all_checks$checks
  expect_equal(all_checks$checks_with_new, sum(ch$New > 0))
  expect_equal(ch$New, sort(ch$New, decreasing = TRUE))
  expect_false(any(grepl("^STR-", ch$ID)))
  expect_true("AE-NEW" %in% ch$ID)
  f <- tool(tools, "check_findings")(check = "AE-NEW")
  expect_gt(f$total_matches, 0)
  expect_true(all(f$rows$VALUE == "[withheld free text]"))
  expect_equal(f$rows$FIELD[1], col_label("AETERM", ctx$study))
  expect_error(tool(tools, "check_findings")(check = "STR-001"), "No review check")
})

