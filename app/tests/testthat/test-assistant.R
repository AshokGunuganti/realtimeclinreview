test_that("a question is logged and answered; errors show as a message", {
  ctx <- test_ctx()
  cfg <- utils::modifyList(assistant_config(ctx$study), list(max_turns = 2L))
  shown <- character()
  stub <- list(stream_async = function(msg) paste("answer to", msg))
  shiny::testServer(assistant_server, args = list(ctx = ctx, cfg = cfg, client_factory = function() stub,
                                                  append = function(r) shown <<- c(shown, r)), {
    session$setInputs(chat_user_input = "How many subjects?")
    expect_equal(shown, "answer to How many subjects?")
    session$setInputs(chat_user_input = "And sites?")
    session$setInputs(chat_user_input = "One more")
    expect_match(shown[3], "limit for one chat")
    session$setInputs(reset = 1)
    expect_equal(turns(), 0L)
  })
  log <- rtcrcore::access_log(ctx$con, ctx$study$id)
  expect_equal(log$DETAIL[log$OBJECT == "question"], c("How many subjects?", "And sites?"))

  shown <- character()
  failing <- list(stream_async = function(msg) stop("HTTP 401 invalid x-api-key sk-ant-abc123"))
  shiny::testServer(assistant_server, args = list(ctx = ctx, cfg = cfg, client_factory = function() failing,
                                                  append = function(r) shown <<- c(shown, r)), {
    session$setInputs(chat_user_input = "Hi")
    expect_match(shown, "API key was refused")
    expect_false(grepl("sk-ant-abc123", shown))
  })
})
